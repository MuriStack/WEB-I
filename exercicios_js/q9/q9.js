console.log("Números de 1 até 20:");
for (let i = 1; i <= 20; i++){
    console.log(i);
}

console.log("Números de 20 até 1:");
for (let i = 20; i >= 1; i--){
    console.log(i);
}

console.log("Números pares de 2 até 20:");
for (let i = 2; i <= 20; i += 2){
    console.log(i);
}

console.log("Múltiplos de 5 entre 5 e 50:");
for (let i = 5; i <= 50; i += 5){
    console.log(i);
}
